"""
Converts full-body hero PNGs into the app's letter-grid sprite format.

Each PNG in MDRNJfitness/Helpers/Sprites/SpriteReferences becomes an avatar
whose id is the file name in snake_case (StartingGirl.png -> "starting_girl").
The output, MDRNJfitness/Helpers/Sprites/AvatarSprites.g.cs, is generated:
edit the PNG and rerun instead of editing it by hand.

PNG rules: 32x32, every pixel fully opaque or fully transparent, at most 62
colours. To show up in the app an avatar also needs an entry in
MDRNJ.Shared/Game/HeroAvatars.cs.

Usage (from the repo root; needs Pillow: pip install pillow):
    python tools/png_to_sprite.py
"""
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "MDRNJfitness" / "Helpers" / "Sprites" / "SpriteReferences"
OUT = ROOT / "MDRNJfitness" / "Helpers" / "Sprites" / "AvatarSprites.g.cs"
SIZE = 32
KEYS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"


def snake_case(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).replace("-", "_").lower()


def convert(png: Path) -> str:
    img = Image.open(png).convert("RGBA")
    if img.size != (SIZE, SIZE):
        sys.exit(f"{png.name}: must be {SIZE}x{SIZE}, is {img.size[0]}x{img.size[1]}")

    palette: dict[tuple[int, int, int], str] = {}
    rows = []
    for y in range(SIZE):
        row = ""
        for x in range(SIZE):
            r, g, b, a = img.getpixel((x, y))
            if a == 0:
                row += "."
                continue
            if a != 255:
                sys.exit(f"{png.name}: pixel ({x},{y}) is semi-transparent (alpha {a}); use 0 or 255")
            if (r, g, b) not in palette:
                if len(palette) == len(KEYS):
                    sys.exit(f"{png.name}: more than {len(KEYS)} colours; reduce the palette")
                palette[(r, g, b)] = KEYS[len(palette)]
            row += palette[(r, g, b)]
        rows.append(row)

    grid = "\n".join(f'                "{row}", // {y}' for y, row in enumerate(rows))
    colours = "\n".join(
        f'                [\'{key}\'] = Color.FromArgb("#{r:02X}{g:02X}{b:02X}"),'
        for (r, g, b), key in palette.items())
    return (f'            ["{snake_case(png.stem)}"] = new SpriteLayer(new[]\n'
            f"            {{\n{grid}\n            }},\n"
            f"            new Dictionary<char, Color>\n"
            f"            {{\n{colours}\n            }}),\n")


def main() -> None:
    pngs = sorted(SRC.glob("*.png"))
    if not pngs:
        sys.exit(f"No PNGs in {SRC}")

    entries = "".join(convert(p) for p in pngs)
    OUT.write_text(
        "// <auto-generated>\n"
        "// Generated by tools/png_to_sprite.py from Helpers/Sprites/SpriteReferences/*.png.\n"
        "// Don't edit by hand: change the PNG and rerun the script.\n"
        "// </auto-generated>\n"
        "namespace MDRNJfitness.Helpers.Sprites\n"
        "{\n"
        "    public static partial class HeroSprites\n"
        "    {\n"
        "        /// <summary>Full-body avatars (one complete drawing, no outfit layers), keyed by avatar id.</summary>\n"
        "        private static readonly Dictionary<string, SpriteLayer> FullBodyAvatars = new(StringComparer.OrdinalIgnoreCase)\n"
        "        {\n"
        f"{entries}"
        "        };\n"
        "    }\n"
        "}\n",
        encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(pngs)} avatar(s): {', '.join(snake_case(p.stem) for p in pngs)})")


if __name__ == "__main__":
    main()
