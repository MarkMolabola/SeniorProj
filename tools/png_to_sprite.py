"""
Converts hero and gear PNGs into the app's letter-grid sprite format.

Hero avatars
    Each PNG directly in MDRNJfitness/Helpers/Sprites/SpriteReferences becomes
    a full-body avatar whose id is the file name in snake_case
    (StartingGirl.png -> "starting_girl"). It also needs an entry in
    MDRNJ.Shared/Game/HeroAvatars.cs to show up in the app.
    -> MDRNJfitness/Helpers/Sprites/AvatarSprites.g.cs

Shop gear
    SpriteReferences/GearReferences/<Slot>/<Name>.png, where <Slot> is Head,
    Top, Bottom, Shoes or Accessory. The item id is the snake_case file name
    (RedCap.png -> "red_cap"). Draw it on the 32x32 hero canvas, only the
    gear's own pixels. Optional per-hero versions: <Name>@<avatar_id>.png
    (e.g. RedCap@starting_girl.png) is used instead when that hero is worn.
    Every item needs a name and price in GearReferences/gear.json:
        { "Head/RedCap": { "name": "Red Cap", "price": 60 } }
    -> MDRNJfitness/Helpers/Sprites/GearSprites.g.cs (art)
    -> MDRNJ.Shared/Game/GearCatalog.g.cs (names, slots, prices for API + app)

PNG rules: 32x32, every pixel fully opaque or fully transparent, at most 62
colours. Generated files shouldn't be edited by hand: change the PNGs and rerun.

Usage (from the repo root; needs Pillow: pip install pillow):
    python tools/png_to_sprite.py
"""
import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SPRITES = ROOT / "MDRNJfitness" / "Helpers" / "Sprites"
SRC = SPRITES / "SpriteReferences"
GEAR_SRC = SRC / "GearReferences"
AVATARS_OUT = SPRITES / "AvatarSprites.g.cs"
GEAR_OUT = SPRITES / "GearSprites.g.cs"
CATALOG_OUT = ROOT / "MDRNJ.Shared" / "Game" / "GearCatalog.g.cs"
SIZE = 32
KEYS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
SLOTS = ["Head", "Top", "Bottom", "Shoes", "Accessory"]
HEADER = ("// <auto-generated>\n"
          "// Generated by tools/png_to_sprite.py from Helpers/Sprites/SpriteReferences.\n"
          "// Don't edit by hand: change the PNGs (or gear.json) and rerun the script.\n"
          "// </auto-generated>\n")


def snake_case(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).replace("-", "_").lower()


def fail(message: str) -> None:
    sys.exit(f"png_to_sprite: {message}")


def layer_code(png: Path, key: str) -> str:
    """A C# dictionary entry: ["key"] = new SpriteLayer(rows, palette)."""
    img = Image.open(png).convert("RGBA")
    if img.size != (SIZE, SIZE):
        fail(f"{png.name}: must be {SIZE}x{SIZE}, is {img.size[0]}x{img.size[1]}")

    palette: dict[tuple[int, int, int], str] = {}
    rows = []
    for y in range(SIZE):
        row = ""
        for x in range(SIZE):
            r, g, b, a = img.getpixel((x, y))
            if a == 0:
                row += "."
                continue
            if a != 255:
                fail(f"{png.name}: pixel ({x},{y}) is semi-transparent (alpha {a}); use 0 or 255")
            if (r, g, b) not in palette:
                if len(palette) == len(KEYS):
                    fail(f"{png.name}: more than {len(KEYS)} colours; reduce the palette")
                palette[(r, g, b)] = KEYS[len(palette)]
            row += palette[(r, g, b)]
        rows.append(row)
    if not palette:
        fail(f"{png.name}: image is empty")

    grid = "\n".join(f'                "{row}", // {y}' for y, row in enumerate(rows))
    colours = "\n".join(
        f'                [\'{k}\'] = Color.FromArgb("#{r:02X}{g:02X}{b:02X}"),'
        for (r, g, b), k in palette.items())
    return (f'            ["{key}"] = new SpriteLayer(new[]\n'
            f"            {{\n{grid}\n            }},\n"
            f"            new Dictionary<char, Color>\n"
            f"            {{\n{colours}\n            }}),\n")


def sprite_file(field: str, summary: str, entries: str) -> str:
    return (HEADER +
            "namespace MDRNJfitness.Helpers.Sprites\n"
            "{\n"
            "    public static partial class HeroSprites\n"
            "    {\n"
            f"        /// <summary>{summary}</summary>\n"
            f"        private static readonly Dictionary<string, SpriteLayer> {field} = new(StringComparer.OrdinalIgnoreCase)\n"
            "        {\n"
            f"{entries}"
            "        };\n"
            "    }\n"
            "}\n")


def build_avatars() -> list[str]:
    pngs = sorted(SRC.glob("*.png"))
    entries = "".join(layer_code(p, snake_case(p.stem)) for p in pngs)
    AVATARS_OUT.write_text(sprite_file(
        "FullBodyAvatars",
        "Full-body avatars (one complete drawing, no outfit layers), keyed by avatar id.",
        entries), encoding="utf-8")
    return [snake_case(p.stem) for p in pngs]


def build_gear() -> list[str]:
    manifest_path = GEAR_SRC / "gear.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}

    layers, catalog, seen = "", "", set()
    for slot in SLOTS:
        for png in sorted((GEAR_SRC / slot).glob("*.png")):
            base, _, avatar = png.stem.partition("@")
            item_id = snake_case(base)
            key = f"{item_id}@{avatar}" if avatar else item_id
            layers += layer_code(png, key)
            if avatar:
                if not (GEAR_SRC / slot / f"{base}.png").exists():
                    fail(f"{slot}/{png.name}: per-hero version needs a default {slot}/{base}.png too")
                continue

            entry = manifest.get(f"{slot}/{base}")
            if not entry or "name" not in entry or "price" not in entry:
                fail(f'{slot}/{png.name}: add "{slot}/{base}": {{"name": ..., "price": ...}} to gear.json')
            if item_id in seen:
                fail(f"{slot}/{png.name}: id '{item_id}' is used twice")
            seen.add(item_id)
            name = str(entry["name"]).replace('"', '\\"')
            catalog += f'            new("{item_id}", "{name}", GearSlot.{slot}, {int(entry["price"])}),\n'

    for folder in GEAR_SRC.glob("*") if GEAR_SRC.exists() else []:
        if folder.is_dir() and folder.name not in SLOTS:
            fail(f"GearReferences/{folder.name}: unknown slot folder; use one of {', '.join(SLOTS)}")

    GEAR_OUT.write_text(sprite_file(
        "GearLayers",
        "Shop gear art keyed by item id, or \"item_id@avatar_id\" for a per-hero version.",
        layers), encoding="utf-8")
    CATALOG_OUT.write_text(
        HEADER +
        "namespace MDRNJ.Shared.Game\n"
        "{\n"
        "    public static partial class GearCatalog\n"
        "    {\n"
        "        /// <summary>Everything the shop sells, from GearReferences/gear.json.</summary>\n"
        "        public static readonly IReadOnlyList<GearItem> All = new GearItem[]\n"
        "        {\n"
        f"{catalog}"
        "        };\n"
        "    }\n"
        "}\n",
        encoding="utf-8")
    return sorted(seen)


def main() -> None:
    avatars = build_avatars()
    gear = build_gear()
    print(f"Avatars ({len(avatars)}): {', '.join(avatars) or 'none'}")
    print(f"Gear ({len(gear)}): {', '.join(gear) or 'none'}")
    for path in (AVATARS_OUT, GEAR_OUT, CATALOG_OUT):
        print(f"  wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
