namespace MDRNJ.Shared.Game
{
    /// <summary>Where a piece of gear is worn. Also the draw order (later slots draw on top).</summary>
    public enum GearSlot
    {
        Bottom = 0,
        Shoes = 1,
        Top = 2,
        Accessory = 3,
        Head = 4
    }

    /// <summary>A gear item. Art lives in the app (HeroSprites.TryGetGear).</summary>
    /// <param name="DropOnly">Never sold: only found in the dungeon (drops and the weekly boss).</param>
    public sealed record GearItem(string Id, string Name, GearSlot Slot, int Price, GearRarity Rarity, StatKind Stat, bool DropOnly = false)
    {
        /// <summary>Stat points added to <see cref="Stat"/> while worn.</summary>
        public int Bonus => GearStats.BonusPoints(Rarity);

        /// <summary>e.g. "+5 STR".</summary>
        public string BonusText => $"+{Bonus} {GearStats.ShortName(Stat)}";
    }

    /// <summary>
    /// Everything the shop sells. The list itself (GearCatalog.g.cs) is
    /// generated by tools/png_to_sprite.py from SpriteReferences/GearReferences
    /// and its gear.json, so the API and the app always agree on items and prices.
    /// </summary>
    public static partial class GearCatalog
    {
        /// <summary>Gear slots in the order the Hero tab shows them.</summary>
        public static readonly IReadOnlyList<GearSlot> DisplayOrder = new[]
        {
            GearSlot.Head, GearSlot.Top, GearSlot.Bottom, GearSlot.Shoes, GearSlot.Accessory
        };

        public static GearItem? Find(string? id) =>
            id is null ? null : All.FirstOrDefault(i => i.Id == id);

        /// <summary>What the shop sells (everything but dungeon-only drops).</summary>
        public static IEnumerable<GearItem> ForSale => All.Where(i => !i.DropOnly);

        public static IEnumerable<GearItem> DungeonDrops => All.Where(i => i.DropOnly);
    }
}
